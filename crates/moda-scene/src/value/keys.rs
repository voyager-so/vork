//! The field names the scene layer and the engine read by name, as an enum: a node's keys compare as integers and
//! take no heap. Any other name (an unknown field, an id used as a key) is held as text by [`super::Key`].
//!
//! Add a name here when code starts reading it; a name missing from the list still works, as text.

macro_rules! known_keys {
    ($($variant:ident = $text:literal,)*) => {
        /// A field name known at compile time.
        #[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
        #[repr(u16)]
        pub enum K { $($variant,)* }

        impl K {
            /// Every known name, in declaration order.
            pub const ALL: &'static [K] = &[$(K::$variant,)*];

            /// The name as the document spells it.
            pub const fn as_str(self) -> &'static str {
                match self { $(K::$variant => $text,)* }
            }

            /// The known name spelled `text`, if there is one.
            pub fn lookup(text: &str) -> Option<K> {
                match text { $($text => Some(K::$variant),)* _ => None }
            }
        }
    };
}

